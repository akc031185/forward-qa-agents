// Pure code generation for the provisioned Playwright + Playwright MCP project.
// Every function returns strings; `generateInfra` returns the full file list.
import { toPascalCase, uniqueNames } from './locators.js';
import type { PageRecord } from './types.js';

export interface GeneratedFile { relPath: string; content: string; kind: string }

export interface InfraOptions {
  targetUrl: string;
  orgSlug: string;
  mcp: boolean;
  generatedAt?: string;
}

function q(s: string): string { return JSON.stringify(s); }

/** `/` -> HomePage, `/about-us` -> AboutUsPage, `/blog/post-1?x=1` -> BlogPost1Page */
export function pageClassName(pathname: string): string {
  const clean = pathname.split('?')[0]!.split('#')[0]!;
  const pascal = toPascalCase(clean.replace(/\.[a-z0-9]+$/i, ''));
  const base = pascal || 'Home';
  return (/^[0-9]/.test(base) ? 'Page' + base : base) + 'Page';
}

export function pageFileName(className: string): string {
  return `${className}.page.ts`;
}

/** Assign unique class names to a crawled page set (stable order). */
export function assignClassNames(pages: PageRecord[]): Map<PageRecord, string> {
  const names = uniqueNames(pages.map(p => pageClassName(p.path)));
  return new Map(pages.map((p, i) => [p, names[i]!]));
}

export function generatePackageJson(opts: InfraOptions): string {
  const scripts: Record<string, string> = {
    test: 'playwright test',
    'test:ui': 'playwright test --ui',
    'test:headed': 'playwright test --headed --project=chromium',
    report: 'playwright show-report',
    ...(opts.mcp ? { mcp: 'npx @playwright/mcp@latest --headless' } : {}),
  };
  return JSON.stringify({
    name: `${opts.orgSlug}-e2e`,
    version: '0.1.0',
    private: true,
    type: 'module',
    description: `Playwright test infrastructure for ${opts.targetUrl}, provisioned by The Forward Deployed Tester.`,
    scripts,
    devDependencies: {
      '@playwright/test': '^1.55.0',
      ...(opts.mcp ? { '@playwright/mcp': '^0.0.40' } : {}),
      '@types/node': '^24.0.0',
      typescript: '^5.8.3',
    },
  }, null, 2) + '\n';
}

